const DEMO_TIME = '2026-09-23T08:00:00.000Z';

function task(id, topic, rawDescription, fields, status) {
  const card = { ...emptyCard(), ...fields };
  return {
    id, rawDescription, topic, card,
    confirmedFields: status === 'published'
      ? Object.keys(card).filter((field) => card[field].trim()) : [],
    status, revision: 1, createdAt: DEMO_TIME, updatedAt: DEMO_TIME,
    publishedAt: status === 'published' ? DEMO_TIME : null,
  };
}

