/** All examples are synthetic. Existing projects are never reseeded or overwritten. */
export function seedDemo(store) {
  return store.transaction(() => {
    if (store.list('tasks').length > 0) return false;
    for (const record of [...draftTasks, ...publishedTasks]) store.put('tasks', record);
    for (const team of teams) {
      if (!store.get('teams', team.id)) store.put('teams', team);
    }
    proposalDetails.forEach(([idea, plan, timeline], index) => {
      const number = index + 1;
      const id = `proposal-demo-${number}`;
      if (!store.get('proposals', id)) store.put('proposals', {
        id, taskId: `task-demo-${number}`, teamId: `team-demo-${number}`,
        idea, plan, timeline, prototypeUrl: `https://example.test/prototypes/demo-${number}`,
        status: 'pending', createdAt: DEMO_TIME, updatedAt: DEMO_TIME,
      });
    });
    return true;
  });
}
